// Regenerates THIRD_PARTY_NOTICES.md from the direct dependencies in package.json.
// Run:  npm run notices
import { readFileSync, writeFileSync } from "node:fs";

const pkg = JSON.parse(readFileSync("package.json", "utf8"));

function describe(name) {
  try {
    const p = JSON.parse(readFileSync(`node_modules/${name}/package.json`, "utf8"));
    const license = typeof p.license === "string" ? p.license : (p.license?.type ?? "see package");
    return { name, version: p.version, license, homepage: p.homepage ?? p.repository?.url ?? "" };
  } catch {
    return { name, version: "?", license: "not installed", homepage: "" };
  }
}

const section = (title, deps) =>
  `## ${title}\n\n| Package | Version | License |\n| --- | --- | --- |\n` +
  Object.keys(deps)
    .sort()
    .map(describe)
    .map((d) => `| ${d.name} | ${d.version} | ${d.license} |`)
    .join("\n") +
  "\n";

const out = `# Third-party notices

This project's own source code is MIT licensed (see LICENSE). It depends on the open-source packages below, each
under its own license; the full texts ship inside each package in \`node_modules\`. This file is generated by
\`npm run notices\` from the direct dependencies in \`package.json\`; transitive dependencies are listed in
\`package-lock.json\`.

Notes:

- UI primitives are generated by shadcn/ui (MIT) and live in \`src/components/ui\`.
- \`cn\` is shadcn's own class-name helper package (MIT, shadcn-ui/cn).
- \`@axe-core/playwright\` (MPL-2.0) is a development-only accessibility test tool and is not shipped to visitors.
- Fonts come from Google Fonts through \`next/font\`; check their licenses (SIL OFL) before redistributing.
- No third-party artwork, icons, or tracking scripts are included. Cloudflare Turnstile is loaded from Cloudflare at
  runtime on pages that show the human check.

${section("Runtime dependencies", pkg.dependencies ?? {})}
${section("Development dependencies", pkg.devDependencies ?? {})}`;

writeFileSync("THIRD_PARTY_NOTICES.md", out);
console.log("Wrote THIRD_PARTY_NOTICES.md");
